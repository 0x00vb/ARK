//! Notebook export: render a project's invocation log and notes as Markdown in a dated,
//! plain, evidence-linked style. This is what makes a session reproducible outside the app —
//! every command is printed to re-run by hand. Fully domain-agnostic.

use crate::error::AgentError;
use ark_core::{InvocationStatus, ProjectId};
use ark_store::Store;
use std::fmt::Write as _;
use time::macros::format_description;

/// Today's date as `YYYY-MM-DD`.
fn today() -> String {
    time::OffsetDateTime::now_utc()
        .format(format_description!("[year]-[month]-[day]"))
        .unwrap_or_default()
}

/// Render a full session log for a project as Markdown.
pub fn render_session_log(store: &Store, project: &ProjectId) -> Result<String, AgentError> {
    let p = store
        .get_project(project)?
        .ok_or_else(|| AgentError::ProjectNotFound(project.to_string()))?;
    let artifacts = store.list_artifacts(project)?;
    let invocations = store.list_invocations(project)?;
    let notes = store.list_notes(project)?;

    let today = today();

    let mut md = String::new();
    let _ = writeln!(md, "# {today} — {}", p.name);
    let _ = writeln!(md);
    if !p.target.is_empty() {
        let _ = writeln!(md, "**Scope:** {}", p.target);
        let _ = writeln!(md);
    }
    let _ = writeln!(
        md,
        "Generated by ARK. Every command below is recorded verbatim and re-runnable.\n"
    );

    // Artifacts
    let _ = writeln!(md, "## Artifacts");
    for a in &artifacts {
        let _ = writeln!(
            md,
            "- `{}` **{}** ({}, {} bytes)",
            a.id.short(),
            a.name,
            a.kind.as_tag(),
            a.size
        );
    }
    let _ = writeln!(md);

    // Invocations
    let _ = writeln!(md, "## What ran");
    for inv in &invocations {
        let mark = match inv.status {
            InvocationStatus::Ok => "✓",
            InvocationStatus::Failed => "✗",
            InvocationStatus::PendingApproval => "⧗ (needs approval)",
            InvocationStatus::Denied => "⊘ (denied)",
            InvocationStatus::Running => "…",
        };
        let dur = inv
            .duration_ms()
            .map(|d| format!(" · {d} ms"))
            .unwrap_or_default();
        let _ = writeln!(md, "\n### {mark} `{}`{dur}", inv.action);
        if let Some(cmd) = &inv.command {
            let _ = writeln!(md, "```\n{}\n```", shell_join(cmd));
        }
        if let Some(err) = &inv.error {
            let _ = writeln!(md, "> error: {err}");
        }
        if !inv.output.is_null() {
            let pretty = serde_json::to_string_pretty(&inv.output).unwrap_or_default();
            let trimmed: String = pretty.lines().take(30).collect::<Vec<_>>().join("\n");
            let _ = writeln!(md, "```json\n{trimmed}\n```");
        }
        if !inv.produced.is_empty() {
            let ids: Vec<String> = inv.produced.iter().map(|i| i.short().to_string()).collect();
            let _ = writeln!(md, "produced: {}", ids.join(", "));
        }
    }
    let _ = writeln!(md);

    // Record — grouped so the reader sees what was established vs. believed.
    if !notes.is_empty() {
        let _ = writeln!(md, "## Record");
        use ark_core::NoteKind::*;
        let groups: &[(ark_core::NoteKind, &str)] = &[
            (Finding, "Findings"),
            (Fact, "Established facts"),
            (Contradiction, "Contradictions"),
            (Hypothesis, "Hypotheses"),
            (Assumption, "Assumptions"),
            (Question, "Open questions"),
            (NextStep, "Next steps"),
            (Evidence, "Evidence"),
            (Note, "Notes"),
        ];
        for (kind, heading) in groups {
            let of_kind: Vec<_> = notes.iter().filter(|n| n.kind == *kind).collect();
            if of_kind.is_empty() {
                continue;
            }
            let _ = writeln!(md, "\n### {heading}");
            for n in of_kind {
                let by = match n.author {
                    ark_core::Author::Agent => " _(agent)_",
                    ark_core::Author::Human => "",
                };
                let cites = if n.cites_invocations.is_empty() {
                    String::new()
                } else {
                    format!(" — cites {} invocation(s)", n.cites_invocations.len())
                };
                let _ = writeln!(md, "- {}{by}{cites}", n.body);
            }
        }
    }

    Ok(md)
}

/// Write a session log into a `<dir>/<date> <name>.md` path and return the path.
pub fn write_session_log(
    store: &Store,
    project: &ProjectId,
    dir: &std::path::Path,
) -> Result<std::path::PathBuf, AgentError> {
    let md = render_session_log(store, project)?;
    std::fs::create_dir_all(dir)?;
    let today = today();
    let p = store.get_project(project)?.unwrap();
    let file = dir.join(format!("{today} {}.md", sanitize(&p.name)));
    std::fs::write(&file, md)?;
    Ok(file)
}

fn shell_join(parts: &[String]) -> String {
    parts
        .iter()
        .map(|p| {
            if p.contains(' ') {
                format!("'{p}'")
            } else {
                p.clone()
            }
        })
        .collect::<Vec<_>>()
        .join(" ")
}

fn sanitize(s: &str) -> String {
    s.chars()
        .map(|c| {
            if c.is_alphanumeric() || c == '-' || c == '_' {
                c
            } else {
                '-'
            }
        })
        .collect()
}
